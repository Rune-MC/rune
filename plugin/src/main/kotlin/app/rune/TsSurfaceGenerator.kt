package app.rune

import io.github.classgraph.ClassGraph
import org.bukkit.plugin.java.JavaPlugin
import java.lang.reflect.Method
import java.lang.reflect.Modifier
import java.lang.reflect.ParameterizedType
import java.lang.reflect.Type
import java.lang.reflect.TypeVariable
import java.lang.reflect.WildcardType
import java.util.ArrayDeque

/**
 * Reflects the Bukkit / Paper / Adventure class surface that's actually
 * loaded on this server and emits a `bukkit.d.ts` containing TypeScript
 * interface declarations for each class.
 *
 * Strategy:
 *   * Start from a seed of the API entry-point classes (Player, Block,
 *     World, ItemStack, ...) plus a handful of supporting types.
 *   * Walk the transitive closure of each seed's superclass + interface
 *     graph, restricted to packages we expose (`org.bukkit.**`,
 *     `io.papermc.paper.**`, `net.kyori.adventure.**`).
 *   * Emit each class as a TS `interface` whose `extends` list mirrors the
 *     Java inheritance graph, with every public *declared* method.
 *
 * Interface merging means these interfaces compose with the hand-curated
 * `rune.d.ts`: the snapshot fields (`name`, `uuid`, `x`, ...) live there;
 * the reflected methods live here.
 */
class TsSurfaceGenerator(private val plugin: JavaPlugin) {

    private val seedNames: List<String> = listOf(
